#include "agino-gpu/configgen.h"

#include <QFile>

namespace AginoGpu {

namespace {

// Decimal Xorg BusID "PCI:<bus>@<domain>:<dev>:<fn>" from the sysfs address "dddd:bb:dd.f"
// (hex in sysfs). Xorg's syntax is "PCI:bus:device:function" with an optional "@domain" after
// the bus; the numbers are decimal. Empty when the address is malformed.
QString xorgBusId(const QString &pciAddress)
{
    const QStringList colon = pciAddress.split(QLatin1Char(':'));
    if (colon.size() != 3)
        return QString();
    const QStringList devFn = colon.at(2).split(QLatin1Char('.'));
    if (devFn.size() != 2)
        return QString();
    bool okDomain = false, okBus = false, okDev = false, okFn = false;
    const uint domain = colon.at(0).toUInt(&okDomain, 16);
    const uint bus = colon.at(1).toUInt(&okBus, 16);
    const uint dev = devFn.at(0).toUInt(&okDev, 16);
    const uint fn = devFn.at(1).toUInt(&okFn, 16);
    if (!okDomain || !okBus || !okDev || !okFn)
        return QString();
    return QStringLiteral("PCI:%1@%2:%3:%4").arg(bus).arg(domain).arg(dev).arg(fn);
}

// True when the file starts with the generated header; *readable says whether it could be read.
bool hasGeneratedHeader(const QString &filePath, bool *readable)
{
    QFile f(filePath);
    if (!f.open(QIODevice::ReadOnly)) {
        *readable = false;
        return false;
    }
    *readable = true;
    return f.readLine() == generatedHeader();
}

} // namespace

QByteArray generatedHeader()
{
    return QByteArrayLiteral("# Generated by agino-gpu; do not edit.\n");
}

QByteArray xorgDedicatedConfig(const Gpu &dgpu)
{
    QByteArray out = generatedHeader();
    if (dgpu.vendor == Vendor::Nvidia) {
        out += QByteArrayLiteral(
            "Section \"OutputClass\"\n"
            "    Identifier \"agino-gpu dedicated\"\n"
            "    MatchDriver \"nvidia-drm\"\n"
            "    Driver \"nvidia\"\n"
            "    Option \"PrimaryGPU\" \"yes\"\n"
            "    ModulePath \"/usr/lib/nvidia/xorg\"\n"
            "    ModulePath \"/usr/lib/xorg/modules\"\n"
            "EndSection\n");
        return out;
    }
    const QString busId = xorgBusId(dgpu.pciAddress);
    if (busId.isEmpty())
        return QByteArray();
    // Xorg driver names: "amdgpu" for AMD, "modesetting" for i915 and xe. The BusID selects the
    // discrete card and leaves the integrated GPU of the same kernel driver alone.
    const QByteArray driver = dgpu.vendor == Vendor::Amd ? QByteArrayLiteral("amdgpu")
                                                         : QByteArrayLiteral("modesetting");
    out += QByteArrayLiteral("Section \"Device\"\n"
                             "    Identifier \"agino-gpu dedicated\"\n"
                             "    Driver \"")
        + driver + QByteArrayLiteral("\"\n    BusID \"") + busId.toLatin1()
        + QByteArrayLiteral("\"\n    Option \"PrimaryGPU\" \"yes\"\nEndSection\n");
    return out;
}

QByteArray modprobeIntegratedConfig(const Gpu &dgpu)
{
    if (dgpu.vendor != Vendor::Nvidia)
        return QByteArray();
    return generatedHeader()
        + QByteArrayLiteral("install nvidia /bin/false\n"
                            "install nvidia_drm /bin/false\n"
                            "install nvidia_modeset /bin/false\n"
                            "install nvidia_uvm /bin/false\n");
}

QList<GeneratedFile> generatedFilesForMode(const Hardware &hw, Mode mode)
{
    QList<GeneratedFile> files;
    const Gpu *dgpu = hw.discreteGpu();
    if (!dgpu)
        return files;
    if (mode == Mode::Integrated) {
        const QByteArray contents = modprobeIntegratedConfig(*dgpu);
        if (!contents.isEmpty())
            files.append({QLatin1String(kModprobeIntegratedPath), contents});
    } else if (mode == Mode::Dedicated) {
        const QByteArray contents = xorgDedicatedConfig(*dgpu);
        if (!contents.isEmpty())
            files.append({QLatin1String(kXorgDedicatedPath), contents});
    }
    return files;
}

QStringList allGeneratedPaths()
{
    return {QLatin1String(kXorgDedicatedPath), QLatin1String(kModprobeIntegratedPath)};
}

bool applyGeneratedFiles(const Root &root, const Hardware &hw, Mode mode, QString *error)
{
    const QList<GeneratedFile> wanted = generatedFilesForMode(hw, mode);

    const auto isOurs = [&root](const QString &path, bool *readable) {
        return hasGeneratedHeader(root.path(path), readable);
    };

    // Pre-flight, before changing anything: refuse only when a path we must write holds a
    // foreign file. A foreign file at a path we would remove is simply not ours to remove.
    for (const GeneratedFile &file : wanted) {
        if (!root.exists(file.path))
            continue;
        bool readable = false;
        if (!isOurs(file.path, &readable)) {
            if (error) {
                *error = readable ? QStringLiteral("%1 exists and was not generated by agino-gpu").arg(file.path)
                                  : QStringLiteral("cannot read %1").arg(file.path);
            }
            return false;
        }
    }

    for (const QString &path : allGeneratedPaths()) {
        bool needed = false;
        for (const GeneratedFile &file : wanted) {
            if (file.path != path)
                continue;
            needed = true;
            if (!root.writeFile(path, file.contents, 0644, error))
                return false;
        }
        bool readable = false;
        if (!needed && root.exists(path) && isOurs(path, &readable) && !root.removeFile(path, error))
            return false;
    }
    return true;
}

} // namespace AginoGpu
